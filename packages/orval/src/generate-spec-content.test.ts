import { mkdtemp, readdir, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';

import type { OpenApiDocument, OutputOptions } from '@orval/core';
import { afterEach, beforeEach, describe, expect, it } from 'vite-plus/test';

import { generateSpecContent } from './generate-spec-content';
import { normalizeOptions } from './utils';

const SPEC: OpenApiDocument = {
  openapi: '3.1.0',
  info: { title: 'Petstore', version: '1.0.0' },
  paths: {
    '/pets': {
      get: {
        operationId: 'listPets',
        parameters: [
          { name: 'limit', in: 'query', schema: { type: 'integer' } },
        ],
        responses: {
          '200': {
            description: 'A list of pets',
            content: {
              'application/json': {
                schema: {
                  type: 'array',
                  items: { $ref: '#/components/schemas/Pet' },
                },
              },
            },
          },
        },
      },
    },
  },
  components: {
    schemas: {
      Pet: {
        type: 'object',
        required: ['id', 'name'],
        properties: {
          id: { type: 'integer' },
          name: { type: 'string' },
          status: { type: 'string', enum: ['available', 'sold'] },
        },
      },
    },
  },
};

describe('generateSpecContent', () => {
  let workspace: string;

  beforeEach(async () => {
    workspace = await mkdtemp(path.join(os.tmpdir(), 'orval-spec-content-'));
  });

  afterEach(async () => {
    await rm(workspace, { recursive: true, force: true });
  });

  const generate = async (output: OutputOptions = {}) =>
    generateSpecContent(
      workspace,
      await normalizeOptions(
        { input: { target: SPEC }, output: { target: './api.ts', ...output } },
        workspace,
      ),
    );

  it('returns the models and the operation types without a client', async () => {
    const content = await generate();

    expect(content).toContain('export interface Pet {');
    expect(content).toContain('export type ListPetsParams = {');
    expect(content).not.toContain('listPets =');
    expect(content).not.toMatch(/^import /m);
    expect(content).not.toContain('axios');
  });

  it('generates one module of type definitions', async () => {
    expect(await generate()).toMatchInlineSnapshot(`
      "/**
       * Generated by orval 🍺
       * Do not edit manually.
       * Petstore
       * OpenAPI spec version: 1.0.0
       */
      export type PetStatus = 'available' | 'sold';
      export interface Pet {
        id: number;
        name: string;
        status?: PetStatus;
      }

      export type ListPetsParams = {
        limit?: number;
      };

      "
    `);
  });

  it('generates enums as unions, which have no runtime value', async () => {
    const content = await generate();

    expect(content).toContain("export type PetStatus = 'available' | 'sold';");
    expect(content).not.toMatch(/^export (const|enum) /m);
  });

  it('writes no file', async () => {
    await generate({ mock: true, clean: true });

    expect(await readdir(workspace)).toEqual([]);
  });

  it.each<[string, OutputOptions]>([
    ['a client', { client: 'react-query', httpClient: 'fetch' }],
    ['a mode', { mode: 'tags-split' }],
    ['a schemas directory', { schemas: './model' }],
    ['mocks', { mock: true }],
    ['a zod client', { client: 'zod' }],
    ['enum declarations', { override: { enumGenerationType: 'enum' } }],
    ['const enums', { override: { enumGenerationType: 'const' } }],
  ])('ignores %s', async (_name, output) => {
    expect(await generate(output)).toBe(await generate());
  });

  it('starts with the header', async () => {
    const content = await generate({
      override: { header: () => '// generated\n' },
    });

    expect(content.startsWith('// generated\n')).toBe(true);
  });
});
